"""Review report generator — Markdown, JSON, and (Phase 6) PDF."""
from __future__ import annotations
import json
from datetime import datetime, timezone
from app.agents.file_reviewer import FileFinding


REPORT_TEMPLATE = """# Code Review Report

**Repository**: `{repo}`
**PR**: #{pr_number} — {pr_title}
**Author**: @{author}
**Commit**: `{head_sha}`
**Reviewed at**: {reviewed_at}
**Decision**: {decision}

---

## Summary

| Severity       | Count |
|----------------|-------|
| 🔴 Critical    | {critical} |
| 🟡 Suggestive  | {suggestive} |
| 🟢 Optimisation| {optimisation} |

---

{findings_section}

---

*Generated by [MACRV](https://github.com/VaibhavBansal26/multi-agent-code-review)*
"""

FINDING_TEMPLATE = """### {index}. [{severity_icon} {severity_upper}] {title}

**File**: `{file_path}`{line_info}

{body}

{suggestion_block}
"""


def generate_report(
    *,
    repo: str,
    pr_number: int,
    pr_title: str,
    author: str,
    head_sha: str,
    decision: str,
    findings: list[FileFinding],
) -> tuple[str, dict]:
    """
    Generate a Markdown report and a structured JSON dict.
    Returns (markdown_str, json_dict).
    """
    critical = [f for f in findings if f.severity == "critical"]
    suggestive = [f for f in findings if f.severity == "suggestive"]
    optimisation = [f for f in findings if f.severity == "optimisation"]

    findings_section = _render_findings(findings)
    reviewed_at = datetime.now(timezone.utc).strftime("%Y-%m-%d %H:%M UTC")

    markdown = REPORT_TEMPLATE.format(
        repo=repo,
        pr_number=pr_number,
        pr_title=pr_title,
        author=author,
        head_sha=head_sha[:8],
        reviewed_at=reviewed_at,
        decision=decision.upper(),
        critical=len(critical),
        suggestive=len(suggestive),
        optimisation=len(optimisation),
        findings_section=findings_section,
    )

    json_data = {
        "repo": repo,
        "pr_number": pr_number,
        "pr_title": pr_title,
        "author": author,
        "head_sha": head_sha,
        "decision": decision,
        "reviewed_at": reviewed_at,
        "summary": {
            "critical": len(critical),
            "suggestive": len(suggestive),
            "optimisation": len(optimisation),
            "total": len(findings),
        },
        "findings": [
            {
                "severity": f.severity,
                "title": f.title,
                "file_path": f.file_path,
                "line_start": f.line_start,
                "line_end": f.line_end,
                "body": f.body,
                "suggestion": f.suggestion,
                "source": f.source,
            }
            for f in findings
        ],
    }

    return markdown, json_data


def _render_findings(findings: list[FileFinding]) -> str:
    if not findings:
        return "✅ No findings — looks good!\n"

    icons = {"critical": "🔴", "suggestive": "🟡", "optimisation": "🟢"}
    parts = []
    for i, f in enumerate(findings, 1):
        line_info = ""
        if f.line_start:
            line_info = f" (line {f.line_start}"
            if f.line_end and f.line_end != f.line_start:
                line_info += f"–{f.line_end}"
            line_info += ")"

        suggestion_block = ""
        if f.suggestion:
            suggestion_block = f"**Suggested fix:**\n```\n{f.suggestion}\n```"

        parts.append(FINDING_TEMPLATE.format(
            index=i,
            severity_icon=icons.get(f.severity, "⚪"),
            severity_upper=f.severity.upper(),
            title=f.title,
            file_path=f.file_path,
            line_info=line_info,
            body=f.body,
            suggestion_block=suggestion_block,
        ))

    return "\n".join(parts)
